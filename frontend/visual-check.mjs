import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_EXECUTABLE||'/usr/bin/chromium',headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1150},deviceScaleFactor:1});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
const screenshot=async name=>page.locator('#habitat').screenshot({path:fileURLToPath(new URL(`../reports/${name}.png`,import.meta.url))});
await page.goto(process.env.TERRARIUM_URL||'http://127.0.0.1:8000',{waitUntil:'networkidle'});
await page.locator('#habitat canvas').waitFor();
await page.waitForTimeout(1800);
assert.equal(await page.locator('#free-camera').isVisible(),false);
const state=await (await page.request.get(new URL('/api/state',page.url()).href)).json();
assert.deepEqual(state.agents.map(agent=>agent.name),['Mac','Cobalt','Cheese','Bluey']);
await screenshot('habitat-revised');console.log('Overview captured.');
for(const [id,name] of ['mac','cobalt','cheese','bluey'].entries()){
 await page.locator(`.resident-nav[data-agent="${id}"]`).dispatchEvent('click');
 await page.waitForTimeout(1400);
 assert.equal(await page.locator('#habitat').getAttribute('data-camera-mode'),'desk');
 assert.equal(await page.locator('#free-camera').isVisible(),true);
 await screenshot(`desk-${name}-revised`);
 console.log(`${name}: desk captured.`);
 await page.locator('#free-camera').click();
 assert.equal(await page.locator('#free-camera').getAttribute('aria-pressed'),'true');
 assert.equal(await page.locator('#habitat').getAttribute('data-camera-mode'),'free');
 const rect=await page.locator('#habitat canvas').boundingBox();
 const x=rect.x+rect.width*.2,y=rect.y+rect.height*.47;
 await page.mouse.move(x,y);await page.mouse.down();
 await page.mouse.move(x+rect.height/(2*.65),y-rect.height*.055,{steps:4});
 await page.mouse.up();await page.waitForTimeout(800);
 await screenshot(`face-${name}-revised`);
 // More than one complete horizontal revolution, without a desk re-selection or azimuth lock.
 await page.mouse.move(x,y);await page.mouse.down();
 await page.mouse.move(x+rect.height/.65*1.15,y,{steps:6});
 await page.mouse.up();await page.waitForTimeout(300);
 assert.equal(await page.locator('#habitat').getAttribute('data-camera-mode'),'free');
 await page.locator('#free-camera').click();
 assert.equal(await page.locator('#habitat').getAttribute('data-camera-mode'),'desk');
 await page.locator('#back-habitat').click();
 assert.equal(await page.locator('#habitat').getAttribute('data-camera-mode'),'overview');
 console.log(`${name}: free orbit and desk reset passed.`);
}
await page.setViewportSize({width:390,height:844});await page.waitForTimeout(1200);
await screenshot('habitat-mobile-revised');
await page.locator('.resident-nav[data-agent="2"]').dispatchEvent('click');
await page.locator('#free-camera').click();
assert.equal(await page.locator('#free-camera').getAttribute('aria-pressed'),'true');
const width=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,viewport:innerWidth}));
assert.ok(width.scroll<=width.viewport);
assert.deepEqual(errors,[]);console.log('All four free-camera controls, mobile layout, and JavaScript error checks passed.');
await browser.close();
