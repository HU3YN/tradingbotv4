import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_EXECUTABLE||'/usr/bin/chromium',headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1536,height:1200},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')console.log('console:',m.text());});
await page.goto('http://127.0.0.1:8000',{waitUntil:'networkidle'});
await page.waitForTimeout(5000);
await page.screenshot({path:fileURLToPath(new URL('../reports/dashboard-desktop.png',import.meta.url)),fullPage:true});
assert.equal(await page.locator('#habitat canvas').count(),1);
assert.equal(await page.locator('.frog-label').count(),4);
console.log('Habitat canvas and four residents rendered.');
await page.locator('.frog-0').click();await page.waitForTimeout(2500);
await page.screenshot({path:fileURLToPath(new URL('../reports/desk-mac.png',import.meta.url))});
assert.equal(await page.locator('#selected-card').isVisible(),true);
console.log('Resident desk interaction passed.');
await page.locator('#back-habitat').click();await page.locator('[data-view="research"]').click();
await page.screenshot({path:fileURLToPath(new URL('../reports/research-desktop.png',import.meta.url))});
assert.equal(await page.locator('#research-view table tbody tr').count(),4);
await page.locator('#settings-nav').click();
assert.equal(await page.locator('#settings-dialog').isVisible(),true);
assert.equal(await page.locator('input[name=secret]').getAttribute('type'),'password');
await page.locator('#settings-dialog .dialog-close').click();
await page.locator('[data-view="habitat"]').click();await page.setViewportSize({width:390,height:844});await page.waitForTimeout(2000);
await page.screenshot({path:fileURLToPath(new URL('../reports/dashboard-mobile.png',import.meta.url)),fullPage:true});
const size=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,viewport:innerWidth}));assert.ok(size.scroll<=size.viewport);console.log('Research table, settings, and mobile layout passed.');await browser.close();
assert.deepEqual(errors,[]);console.log('No JavaScript errors.');
